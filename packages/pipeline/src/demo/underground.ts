import {
  makeId,
  type Category,
  type Entity,
  type GuideEntry,
  type Location,
  type PackData,
  type TileSource,
} from '@atlas/schema';
import { pyramidMaxZoom } from '@atlas/core';
import { createRandom, deriveSeed, pick } from '../random';
import { elevationAt, type Terrain } from './terrain';
import { DEMO_GAME_ID } from './content';

const id = (kind: Parameters<typeof makeId>[1], local: string) => makeId(DEMO_GAME_ID, kind, local);

export const DEEP_MAP_ID = id('map', 'deep');

export interface UndergroundLayer {
  local: string;
  name: string;
  terrain: Terrain;
  tiles: TileSource;
}

export interface UndergroundOptions {
  seed: number;
  /** Edge length of the square map image. */
  size: number;
  tileSize: number;
  /** Locations on each layer. */
  locationsPerLayer: number;
  layers: readonly UndergroundLayer[];
}

/** Share of each category among the underground locations. */
const MIX: readonly { category: string; share: number; names: readonly string[] }[] = [
  { category: 'relic', share: 0.3, names: ['Relic shard'] },
  { category: 'chest', share: 0.2, names: ['Weathered chest', 'Iron-bound chest'] },
  { category: 'key', share: 0.15, names: ['Rusted key', 'Bone key', 'Glass key'] },
  { category: 'den', share: 0.12, names: ['Spider nest', 'Bat roost'] },
  { category: 'elite', share: 0.15, names: ['Stone warden', 'Hollow king'] },
  { category: 'door', share: 0.08, names: ['Sealed door'] },
];

/**
 * Adds a second map to the demo pack: "The Hollow Deep", a cave system with
 * one tile layer per level, so map and layer switching can be tried out.
 * Location ids are `demo:loc:deep-NNNN`, independent of the surface count.
 */
export function addUnderground(data: PackData, options: UndergroundOptions): PackData {
  const random = createRandom(deriveSeed(options.seed, 'underground'));
  const categories = new Map<string, Category>(data.categories.map((c) => [c.id, c]));
  const maxZoom = pyramidMaxZoom(options.size, options.size, options.tileSize);
  const locations: Location[] = [];
  const margin = 48;

  for (const layer of options.layers) {
    const layerId = id('layer', layer.local);
    for (let n = 0; n < options.locationsPerLayer; n++) {
      let roll = random();
      const spec = MIX.find((entry) => (roll -= entry.share) < 0) ?? MIX[0]!;
      const category = categories.get(id('cat', spec.category));
      if (!category) throw new Error(`Unknown demo category ${spec.category}`);
      let x = 0;
      let y = 0;
      for (let attempt = 0; attempt < 500; attempt++) {
        x = Math.round(margin + random() * (options.size - 2 * margin));
        y = Math.round(margin + random() * (options.size - 2 * margin));
        if (elevationAt(layer.terrain, x, y) > 0.02) break;
      }
      const local = `deep-${String(locations.length + 1).padStart(4, '0')}`;
      locations.push({
        id: id('loc', local),
        mapId: DEEP_MAP_ID,
        layerId,
        x,
        y,
        categoryId: category.id,
        regionId: null,
        name: `${pick(random, spec.names)} ${n + 1}`,
        entityIds: spec.category === 'key' ? [id('entity', 'old-key')] : [],
        guideId: spec.category === 'key' || spec.category === 'door' ? id('guide', 'keys') : null,
        since: data.manifest.packVersion,
      });
    }
  }

  const keyEntity: Entity = {
    id: id('entity', 'old-key'),
    name: 'Old key',
    kind: 'item',
    description: 'Opens one sealed door in the Hollow Deep.',
  };
  const keysGuide: GuideEntry = {
    id: id('guide', 'keys'),
    title: 'Keys and sealed doors',
    body: [
      'Every **sealed door** in the Hollow Deep opens with one old key.',
      '',
      'Keys turn up on both levels; switch between *Upper galleries* and *Lower galleries* with the layer buttons.',
      '',
      'This demo world is generated by code; the [Atlas source](https://github.com/DrFlGd/atlas) explains how.',
    ].join('\n'),
    locationIds: locations
      .filter((l) => l.guideId === id('guide', 'keys'))
      .slice(0, 10)
      .map((l) => l.id),
  };

  return {
    ...data,
    maps: [
      ...data.maps,
      { id: DEEP_MAP_ID, name: 'The Hollow Deep', width: options.size, height: options.size },
    ],
    layers: [
      ...data.layers,
      ...options.layers.map((layer) => ({
        id: id('layer', layer.local),
        mapId: DEEP_MAP_ID,
        name: layer.name,
        tiles: layer.tiles,
        minZoom: 0,
        maxZoom,
        tileSize: options.tileSize,
      })),
    ],
    locations: [...data.locations, ...locations],
    entities: [...data.entities, keyEntity],
    guides: [...data.guides, keysGuide],
  };
}

/**
 * Recolours a rendered relief image as cave rock: brightness is kept, hue is
 * replaced by `tint`, and water becomes a dark chasm.
 */
export function tintAsCave(image: Buffer, tint: readonly [number, number, number]): Buffer {
  const out = Buffer.alloc(image.length);
  for (let i = 0; i < image.length; i += 3) {
    const r = image[i]!;
    const g = image[i + 1]!;
    const b = image[i + 2]!;
    const water = b > r + 25 && b > g;
    const light = (0.3 * r + 0.59 * g + 0.11 * b) / 255;
    const level = water ? 0.12 + light * 0.25 : 0.25 + light * 0.75;
    out[i] = Math.min(255, tint[0] * level);
    out[i + 1] = Math.min(255, tint[1] * level);
    out[i + 2] = Math.min(255, tint[2] * level);
  }
  return out;
}
