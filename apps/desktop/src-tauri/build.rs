/// Where tauri-build writes a permission file per command.
const AUTOGENERATED: &str = "permissions/autogenerated";

fn main() {
    let downloads = env::var_os("CARGO_FEATURE_DOWNLOADS").is_some();
    let commands: &'static [&'static str] = if downloads {
        COMMANDS
            .iter()
            .chain(DOWNLOAD_COMMANDS)
            .copied()
            .collect::<Vec<_>>()
            .leak()
    } else {
        COMMANDS
    };
    forget_other_commands(commands);
    // `capabilities/main.json` grants the commands of every build to the main
    // window; `capabilities/downloads/` adds the download commands, and is
    // read only when they exist, since a capability naming a command that
    // does not exist stops the build.
    println!("cargo:rerun-if-changed=capabilities");
    let capabilities = if downloads {
        "./capabilities/**/*"
    } else {
        "./capabilities/*"
    };
    // The web app may call only these commands, and only where a capability
    // grants them.
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .capabilities_path_pattern(capabilities)
            .app_manifest(tauri_build::AppManifest::new().commands(commands)),
    )
    .expect("failed to run the Tauri build script");
}

/// Removes the permission files of commands this build does not have, left
/// by a build with other features, so no permission names a missing command.
fn forget_other_commands(commands: &[&str]) {
    let Ok(entries) = fs::read_dir(Path::new(AUTOGENERATED)) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let stem = path.file_stem().and_then(|stem| stem.to_str());
        let is_command_file = path.extension().is_some_and(|ext| ext == "toml");
        if is_command_file && stem.is_some_and(|stem| !commands.contains(&stem)) {
            let _ = fs::remove_file(&path);
        }
    }
}
